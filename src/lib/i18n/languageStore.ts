export function translate(key: string, lang: LanguageCode = currentLanguage): string {
  return TRANSLATIONS[lang]?.[key] || TRANSLATIONS.en[key] || key;
}

export function useLanguage() {
  const [lang, setLang] = useState<LanguageCode>(languageStore.getLanguage());

  useEffect(() => {
    if (typeof window !== "undefined") {
      const saved = localStorage.getItem("bhoomitra_lang") as LanguageCode;
      if (saved && SUPPORTED_LANGUAGES.some((l) => l.code === saved)) {
        languageStore.setLanguage(saved);
      }
    }
    return languageStore.subscribe((newLang) => setLang(newLang));
  }, []);

  return {
    language: lang,
    setLanguage: languageStore.setLanguage,
    languages: SUPPORTED_LANGUAGES,
    t: (key: string) => translate(key, lang),
  };
}
